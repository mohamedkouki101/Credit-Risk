"""Out-of-time split materialisation (D-06, T-02). Never random.

``make_splits`` assigns rows by issue month using ``configs/splits.yaml``:

- ``train`` / ``valid`` / ``test``: modelled rows only (``y`` is set, so core population
  with a determinate status) issued inside each window.
- ``monitor``: rows issued 2016-01 to 2018-12 with the population's application type and
  **any term** (data plan 5.5). Outcomes are not mature, so the parquet has no ``y``.

``check_splits`` is T-02: each split's last issue date is strictly before the next split's
first, and no loan id appears in two splits. The ``features`` stage writes
``data/processed/{train,valid,test,monitor}.parquet`` and ``results/split_summary.csv``,
and fills the split section of ``reports/data_profile.md``.
"""

from __future__ import annotations

from dataclasses import dataclass
from itertools import pairwise
from pathlib import Path

import pandas as pd

from credit_risk.config import (
    REPO_ROOT,
    MonthRange,
    SplitsConfig,
    load_all_configs,
    load_base_config,
)

SPLIT_NAMES = ("train", "valid", "test", "monitor")
SPLITS_START = "<!-- generated:splits:start -->"
SPLITS_END = "<!-- generated:splits:end -->"


class SplitError(AssertionError):
    """The splits overlap in time, share a loan id, or one is empty (T-02)."""


@dataclass(frozen=True)
class FeaturesStageOutputs:
    split_parquets: dict[str, Path]
    summary_csv: Path
    profile_md: Path


def _in_window(issue: pd.Series, win: MonthRange) -> pd.Series:
    month = issue.dt.strftime("%Y-%m")
    return (month >= win.start) & (month <= win.end)


def make_splits(
    df: pd.DataFrame, cfg: SplitsConfig, application_type: str = "Individual"
) -> dict[str, pd.Index]:
    """Row index of each split, in the order train, valid, test, monitor."""
    issue = df[cfg.date_column]
    labelled = df["y"].notna()
    out = {
        name: df.index[labelled & _in_window(issue, win)]
        for name, win in (("train", cfg.train), ("valid", cfg.valid), ("test", cfg.test))
    }
    monitor = _in_window(issue, cfg.monitor) & (df["application_type"] == application_type)
    out["monitor"] = df.index[monitor]
    return out


def check_splits(
    df: pd.DataFrame, splits: dict[str, pd.Index], date_column: str = "issue_d"
) -> None:
    """T-02: raise ``SplitError`` unless splits are non-empty, time-ordered and id-disjoint."""
    for name, idx in splits.items():
        if len(idx) == 0:
            raise SplitError(f"split {name!r} is empty")
    for (a, ia), (b, ib) in pairwise(splits.items()):
        if df.loc[ia, date_column].max() >= df.loc[ib, date_column].min():
            raise SplitError(f"date order broken: {a} reaches into {b}")
    seen: dict[str, str] = {}
    for name, idx in splits.items():
        for loan_id in df.loc[idx, "id"]:
            if loan_id in seen:
                raise SplitError(f"loan id {loan_id!r} is in both {seen[loan_id]} and {name}")
            seen[loan_id] = name


def split_summary(df: pd.DataFrame, splits: dict[str, pd.Index]) -> pd.DataFrame:
    """Per split: rows, first/last issue month, bads and bad rate (NaN for ``monitor``)."""
    rows = []
    for name, idx in splits.items():
        part = df.loc[idx]
        labelled = name != "monitor"
        n_bad = int(part["y"].eq(1).sum()) if labelled else None
        rows.append(
            {
                "split": name,
                "rows": len(part),
                "first_month": part["issue_d"].min().strftime("%Y-%m"),
                "last_month": part["issue_d"].max().strftime("%Y-%m"),
                "n_bad": n_bad,
                "bad_rate": n_bad / len(part) if n_bad is not None else float("nan"),
            }
        )
    return pd.DataFrame(rows)


def render_split_section(summary: pd.DataFrame) -> str:
    """The marked split section of ``reports/data_profile.md``."""
    lines = [
        SPLITS_START,
        "## Splits",
        "",
        "Generated by `uv run python -m credit_risk features` from `results/split_summary.csv`.",
        "Out-of-time on issue month (T-02 checked). `monitor` is unlabelled.",
        "",
        "| Split | Rows | Issue months | Bad | Bad rate |",
        "|---|---:|---|---:|---:|",
    ]
    for r in summary.itertuples(index=False):
        labelled = r.split != "monitor"
        bad = f"{int(r.n_bad):,}" if labelled else "n/a"
        rate = f"{r.bad_rate:.2%}" if labelled else "unlabelled"
        lines.append(
            f"| {r.split} | {r.rows:,} | {r.first_month} to {r.last_month} | {bad} | {rate} |"
        )
    lines.append(SPLITS_END)
    return "\n".join(lines)


def _replace_section(document: str, section: str) -> str:
    if SPLITS_START not in document or SPLITS_END not in document:
        raise ValueError("split-section markers not found in the data profile")
    head, rest = document.split(SPLITS_START, 1)
    _, tail = rest.split(SPLITS_END, 1)
    return f"{head}{section}{tail}"


def run_features_stage(
    interim_dir: Path | None = None,
    processed_dir: Path | None = None,
    results_dir: Path | None = None,
    reports_dir: Path | None = None,
) -> FeaturesStageOutputs:
    """Read ``loans_clean.parquet``, cut the splits, check T-02, write the outputs."""
    cfg = load_all_configs()
    paths = load_base_config().paths
    interim_dir = interim_dir or REPO_ROOT / paths.data_interim
    processed_dir = processed_dir or REPO_ROOT / paths.data_processed
    results_dir = results_dir or REPO_ROOT / paths.results
    reports_dir = reports_dir or REPO_ROOT / paths.reports
    for d in (processed_dir, results_dir):
        d.mkdir(parents=True, exist_ok=True)

    table = pd.read_parquet(interim_dir / "loans_clean.parquet")
    splits = make_splits(table, cfg.splits, cfg.target.population.application_type)
    check_splits(table, splits, cfg.splits.date_column)

    parquets = {}
    for name, idx in splits.items():
        part = table.loc[idx].reset_index(drop=True)
        if name == "monitor":
            part = part.drop(columns=["y"])
        parquets[name] = processed_dir / f"{name}.parquet"
        part.to_parquet(parquets[name], index=False)

    summary = split_summary(table, splits)
    summary_csv = results_dir / "split_summary.csv"
    summary.to_csv(summary_csv, index=False, lineterminator="\n")
    profile_md = reports_dir / "data_profile.md"
    text = profile_md.read_text(encoding="utf-8")
    profile_md.write_text(
        _replace_section(text, render_split_section(summary)), encoding="utf-8", newline="\n"
    )
    return FeaturesStageOutputs(parquets, summary_csv, profile_md)
